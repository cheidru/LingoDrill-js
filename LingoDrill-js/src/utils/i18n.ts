/** Values substituted into `{name}` placeholders. */
export type Params = Record<string, string | number>

function lookup(key: string, lang: Language): string {
  const dict = translations[lang] ?? translations.en
  return dict[key] ?? translations.en[key] ?? key
}

function fill(s: string, params?: Params): string {
  if (!params) return s
  return s.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole
  )
}

/* Which plural form `n` takes. English has two, Russian three: 1 but not 11,
   2–4 but not 12–14, everything else. Counted keys therefore need `.one` and
   `.other` in English and `.one`, `.few` and `.many` in Russian — a missing
   Russian form would fall through to an English key that does not exist and
   surface as the raw key, so all three must be written out. */
function pluralForm(n: number, lang: Language): "one" | "few" | "many" | "other" {
  if (lang === "ru") {
    const mod10 = n % 10
    const mod100 = n % 100
    if (mod10 === 1 && mod100 !== 11) return "one"
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few"
    return "many"
  }
  return n === 1 ? "one" : "other"
}

export function t(key: string, params?: Params, lang: Language = getLanguage()): string {
  return fill(lookup(key, lang), params)
}

/** Counted string: picks `<key>.<form>` and fills `{n}` with the count. */
/* `params` covers counted strings that also carry a placeholder besides {n};
   {n} is supplied automatically and wins over any n passed in. */
export function tn(
  key: string,
  n: number,
  params?: Params,
  lang: Language = getLanguage(),
): string {
  return t(`${key}.${pluralForm(n, lang)}`, { ...params, n }, lang)
}

/* Translate bound to the active language. `t.n` is the counted variant, hung
   off the same function so a component needs only the one hook — and so the
   many existing `const t = useT()` call sites keep working unchanged. */
export type TFunc = ((key: string, params?: Params) => string) & {
  n: (key: string, count: number, params?: Params) => string
}

/* Built outside the hook: hanging `.n` off the function is a mutation, and the
   React compiler treats anything created inside a hook body as immutable. */
function makeT(lang: Language): TFunc {
  const fn = ((key: string, params?: Params) => t(key, params, lang)) as TFunc
  fn.n = (key: string, count: number, params?: Params) => tn(key, count, params, lang)
  return fn
}

export function useT(): TFunc {
  const [lang, setLang] = useState<Language>(getLanguage())
  useEffect(() => {
    const onChange = (e: Event) => {
      const detail = (e as CustomEvent).detail as Language
      setLang(detail)
    }
    window.addEventListener("lingodrill:languagechange", onChange)
    return () => window.removeEventListener("lingodrill:languagechange", onChange)
  }, [])
  return useMemo(() => makeT(lang), [lang])
}
